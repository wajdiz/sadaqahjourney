/* Merge Arabic overlay into the main module arrays so views can read *_ar
   fields directly from each item via the L() helper. Called once at boot. */
window.mergeArabic = function () {
  const D = window.SADAQAH_DATA;
  const AR = window.SADAQAH_AR;
  if (!D || !AR) return;
  D.MODULE_A.forEach((s) => { Object.assign(s, AR.stories[s.id] || {}); });
  D.MODULE_B.forEach((p) => {
    const a = AR.impact[p.id]; if (!a) return;
    Object.assign(p, a);
    if (a.years_ar) p.years.forEach((y, i) => { if (a.years_ar[i]) Object.assign(y, a.years_ar[i]); });
  });
  D.MODULE_C.forEach((g) => g.games.forEach((gm) => Object.assign(gm, AR.games[gm.id] || {})));
  D.MODULE_D.guidelines.forEach((g, i) => Object.assign(g, AR.guidelines[i] || {}));
  D.MODULE_D.samples.forEach((s, i) => Object.assign(s, AR.samples[i] || {}));
};
